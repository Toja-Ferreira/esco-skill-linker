"""Read the queries where Portuguese fails and English does not.

Experiment 07 found the aggregate gap is produced by a tail. Roughly 90% of
Portuguese queries behave like English ones; the worst 5 to 10% carry the
difference. The correlation between per-query difficulty in the two languages is
0.321, so each language fails on its own set rather than on inherently hard
occupations.

Aggregate statistics cannot go further than that. This dumps the worst
language-specific failures side by side for reading: the query text, the gold
skills, and what outranked them. The output is committed so any pattern claimed
from it can be checked against the same cases.

Selection: occupations ranked by how much worse one language does than the
other, measured on the number of non-gold skills outranking the best gold skill.

Writes:
    results/failure_cases.md

Usage:
    python -m experiments.08_failure_cases
    python -m experiments.08_failure_cases --language en --n 5
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from src.retrieval.bm25 import (BM25Index, build_documents, get_stemmer,
                                get_stopwords, tokenize)

REPO_ROOT = Path(__file__).resolve().parents[1]
PROCESSED = REPO_ROOT / "data" / "processed"
BENCHMARK = REPO_ROOT / "data" / "benchmark"
RESULTS = REPO_ROOT / "results"

LANGUAGES = ("pt", "en")
VARIANT = "labels_desc"
TOP_SHOWN = 10


def language_data(texts, labels, skills, lang: str):
    skill_uris = sorted(skills["conceptUri"])
    t = texts[texts["language"] == lang]
    preferred = dict(zip(t["conceptUri"], t["preferredLabel"]))
    description = dict(zip(t["conceptUri"], t["description"]))
    a = labels[(labels["language"] == lang) & (labels["labelType"] == "alt")]
    alt: dict[str, list[str]] = {}
    for uri, label in zip(a["conceptUri"], a["label"]):
        alt.setdefault(uri, []).append(label)
    return skill_uris, preferred, alt, description


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--language", default="pt", choices=list(LANGUAGES),
                    help="the language whose failures to inspect")
    ap.add_argument("--n", type=int, default=8)
    ap.add_argument("--split", default="test", choices=["test", "dev"])
    args = ap.parse_args()

    other = "en" if args.language == "pt" else "pt"

    per_query = pd.read_csv(RESULTS / "score_distribution_per_query.csv")
    piv = per_query.pivot(index="occupationUri", columns="language",
                          values="n_outranking")
    # Worst cases for one language relative to the other, so shared difficulty
    # is filtered out rather than dominating the selection.
    piv["excess"] = piv[args.language] - piv[other]
    worst = piv.sort_values("excess", ascending=False).head(args.n)

    splits = pd.read_csv(BENCHMARK / "splits.csv")
    splits = splits[splits["split"] == args.split]
    texts = pd.read_parquet(PROCESSED / "texts.parquet")
    labels = pd.read_parquet(PROCESSED / "labels.parquet")
    skills = pd.read_parquet(PROCESSED / "skills.parquet")
    rel = pd.read_parquet(PROCESSED / "occupation_skill_relations.parquet")

    ess = rel[rel["relationType"] == "essential"]
    gold: dict[str, set[str]] = {}
    for occ, skill in zip(ess["occupationUri"], ess["skillUri"]):
        gold.setdefault(occ, set()).add(skill)

    indexes, lookups = {}, {}
    for lang in LANGUAGES:
        skill_uris, preferred, alt, description = language_data(
            texts, labels, skills, lang)
        docs = build_documents(skill_uris, preferred, alt, description, VARIANT)
        indexes[lang] = BM25Index(skill_uris, docs, get_stemmer(lang),
                                  get_stopwords(lang))
        occ = texts[(texts["language"] == lang)
                    & (texts["conceptKind"] == "occupation")]
        lookups[lang] = {
            "uris": skill_uris,
            "pos": {u: i for i, u in enumerate(skill_uris)},
            "skill_label": preferred,
            "occ_label": dict(zip(occ["conceptUri"], occ["preferredLabel"])),
            "occ_desc": dict(zip(occ["conceptUri"], occ["description"])),
        }

    out: list[str] = []
    w = out.append
    w(f"# Failure cases: {args.language} much worse than {other}\n")
    w(f"The {args.n} occupations where `{args.language}` has the largest excess "
      f"of non-gold skills outranking its best gold skill, relative to "
      f"`{other}` on the same occupation. Ranking by excess rather than by raw "
      f"count filters out occupations that are simply hard in both languages.\n")
    w(f"Configuration: {VARIANT}, stemmed, stopwords removed, BM25 defaults, "
      f"`{args.split}` split.\n")
    w("Generated by `experiments/08_failure_cases.py`. Committed so any pattern "
      "claimed from these cases can be checked against them.\n")

    for occ_uri, row in worst.iterrows():
        L = lookups[args.language]
        w("---\n")
        w(f"## {L['occ_label'][occ_uri]}\n")
        w(f"`{occ_uri.rsplit('/', 1)[-1]}`  ")
        w(f"non-gold outranking best gold: **{args.language} "
          f"{int(row[args.language])}**, {other} {int(row[other])}\n")

        for lang in (args.language, other):
            w(f"**{lang} description**  ")
            w(f"{lookups[lang]['occ_desc'][occ_uri]}\n")

        gold_uris = gold[occ_uri]
        w(f"**Gold skills ({len(gold_uris)} essential)**\n")
        for u in sorted(gold_uris, key=lambda x: L["skill_label"].get(x, "")):
            w(f"- {L['skill_label'].get(u, '?')}  \n"
              f"  *{lookups[other]['skill_label'].get(u, '?')}*")
        w("")

        for lang in (args.language, other):
            idx, LK = indexes[lang], lookups[lang]
            q = tokenize(LK["occ_desc"][occ_uri], idx.stemmer, idx.stopwords)
            scores = idx.bm25.get_scores(q)
            order = np.argsort(-scores, kind="stable")[:TOP_SHOWN]

            w(f"**Top {TOP_SHOWN} retrieved, {lang}**\n")
            w("| rank | score | gold | skill |")
            w("|---:|---:|:---:|---|")
            for rank, pos in enumerate(order, 1):
                uri = LK["uris"][pos]
                mark = "**Y**" if uri in gold_uris else ""
                w(f"| {rank} | {scores[pos]:.2f} | {mark} | "
                  f"{LK['skill_label'].get(uri, '?')} |")
            w("")

            gold_pos = [LK["pos"][u] for u in gold_uris if u in LK["pos"]]
            gs = scores[gold_pos]
            best = int(np.argmax(gs))
            best_uri = [u for u in gold_uris if u in LK["pos"]][best]
            rank_of_best = int((scores > gs.max()).sum()) + 1
            w(f"Best-scoring gold skill in {lang}: "
              f"*{LK['skill_label'].get(best_uri, '?')}* "
              f"at rank {rank_of_best}, score {gs.max():.2f}. "
              f"Gold scores range {gs.min():.2f} to {gs.max():.2f}.\n")

    RESULTS.mkdir(exist_ok=True)
    path = RESULTS / "failure_cases.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {path.relative_to(REPO_ROOT)} ({args.n} cases)")
    print(f"\nWorst {args.language} excess:")
    for occ_uri, row in worst.iterrows():
        print(f"  {int(row['excess']):>5}  "
              f"{lookups[args.language]['occ_label'][occ_uri][:60]}")


if __name__ == "__main__":
    main()